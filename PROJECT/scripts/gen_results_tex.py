#!/usr/bin/env python3
"""Write report_ieee/generated/results.tex (numbers and table rows) from results/eval/*: python3 scripts/gen_results_tex.py"""
import csv
import json
import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EV = os.path.join(ROOT, "results", "eval")
OUT = os.path.join(ROOT, "report_ieee", "generated")


def rows(name):
    with open(os.path.join(EV, name)) as f:
        return list(csv.DictReader(f))


def f3(x):
    x = float(x)
    return "--" if x != x else "%.3f" % x


def f2(x):
    x = float(x)
    return "--" if x != x else "%.2f" % x


def main():
    os.makedirs(OUT, exist_ok=True)
    summ = json.load(open(os.path.join(EV, "summary.json")))
    ov = {r["method"]: r for r in rows("overall.csv")}
    m = {}
    c, eta, tau = math.log(4), math.log(99), 600.0
    lim = tau * math.log(1 / (1 - c / eta))
    m["SlowLimit"] = "%.0f" % lim
    m["SlowRate"] = "%.4f" % (1 / lim)
    m["NRuns"] = str(summ["runs"])
    m["NTest"] = str(summ["test_runs"])
    m["NPkts"] = "{:,}".format(summ["packets"]).replace(",", "\\,")
    m["NAttempts"] = "{:,}".format(summ["attempts"]).replace(",", "\\,")
    key = {"AIS-SPRT (ours)": "Ours", "TRW": "TRW", "IA-Window": "IA", "Naive-Window": "Naive", "Entropy": "Ent",
           "Random Forest": "RF"}
    for meth, k in key.items():
        r = ov[meth]
        m[k + "TPR"] = f3(r["TPR"])
        m[k + "FPR"] = f3(r["FPR"])
        m[k + "Fone"] = f3(r["F1"])
        m[k + "Prec"] = f3(r["precision"])
        m[k + "FP"] = r["FP"]
        m[k + "TP"] = r["TP"]
        m[k + "P"] = r["P"]
        m[k + "N"] = r["N"]
        m[k + "Delay"] = f2(r["delay_med_s"])
    tab = []
    for meth in key:
        r = ov[meth]
        name = "\\textbf{AIS-SPRT (ours)}" if "ours" in meth else meth
        vals = [f3(r["TPR"]), f3(r["FPR"]), f3(r["precision"]), f3(r["F1"]), f2(r["delay_med_s"])]
        if "ours" in meth:
            vals = ["\\textbf{%s}" % v for v in vals]
        tab.append("%s & %s \\\\" % (name, " & ".join(vals)))
    m["OverallRows"] = "\n".join(tab)
    with open(os.path.join(OUT, "results.tex"), "w") as f:
        f.write("% generated by scripts/gen_results_tex.py -- do not edit\n")
        for k, v in m.items():
            f.write("\\newcommand{\\%s}{%s}\n" % (k, v))
    print("\n".join("%s = %s" % (k, v.replace("\n", " | ")) for k, v in m.items()))


if __name__ == "__main__":
    main()
