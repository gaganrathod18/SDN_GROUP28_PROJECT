#ifndef PACMAN_TYPES_H
#define PACMAN_TYPES_H

#include <chrono>
#include <cstdint>
#include <map>
#include <string>
#include <unordered_map>
#include <vector>

namespace PacMan {

/**
 * @brief Network Layer 4 protocols monitored by PacMan.
 * The underlying values match standard IP protocol numbers (IANA).
 */
enum class Protocol {
    TCP = 6,     ///< Transmission Control Protocol
    UDP = 17,    ///< User Datagram Protocol
    OTHER = 0    ///< ICMP or any other unclassified protocol
};

/**
 * @brief Threat and intrusion alert severity level.
 */
enum class Severity {
    LOW,         ///< Low risk, informational alerts
    MEDIUM,      ///< Medium risk, anomalies needing attention
    HIGH         ///< High risk, critical threats (causes automatic IP block)
};

/**
 * @brief Unique identifier for a network flow (5-tuple).
 */
struct FlowKey {
    std::string src_ip;                  ///< Source IP Address
    std::string dst_ip;                  ///< Destination IP Address
    std::uint16_t src_port = 0;          ///< Source Port Number (0 if not applicable)
    std::uint16_t dst_port = 0;          ///< Destination Port Number (0 if not applicable)
    Protocol protocol = Protocol::OTHER; ///< Layer 4 Protocol

    /**
     * @brief Compare two flow keys for exact equality.
     */
    [[nodiscard]] bool operator==(const FlowKey& other) const;

    /**
     * @brief Get a human-readable string representation of the flow key.
     */
    [[nodiscard]] std::string toString() const;
};

/**
 * @brief Hash calculator for FlowKey to allow its use in std::unordered_map.
 */
struct FlowKeyHash {
    [[nodiscard]] std::size_t operator()(const FlowKey& key) const;
};

/**
 * @brief Active flow session state and tracking statistics.
 */
struct Flow {
    FlowKey key;                                ///< The 5-tuple identifier
    std::string hostname;                       ///< Extracted domain/hostname (via SNI/DNS/HTTP Host)
    std::string classification = "Unknown";     ///< Classified category or application name
    std::uint64_t packets = 0;                  ///< Total packets counted in this flow
    std::uint64_t bytes = 0;                    ///< Total bytes counted in this flow
    std::chrono::system_clock::time_point first_seen; ///< Timestamp of the first packet in flow
    std::chrono::system_clock::time_point last_seen;  ///< Timestamp of the last packet in flow
    std::string connection_state = "—";          ///< Connection state tag (e.g., SYN, ESTAB, RST)
    std::string dst_country = "—";              ///< "LAN" for private destinations, "—" otherwise (no GeoIP database)
    std::string tls_version = "—";              ///< TLS version detected (if HTTPS)
    std::string cipher_suite = "—";             ///< Negotiated TLS cipher suite
    std::string ja3_fingerprint = "—";          ///< Computed JA3 client fingerprint
};

/**
 * @brief Captured DNS query record.
 */
struct DnsQuery {
    std::chrono::system_clock::time_point timestamp; ///< Time when the query was captured
    std::string query;                               ///< Query string (domain queried)
    std::string source_ip;                           ///< IP that made the query
};

/**
 * @brief Summary details of domains checked against threat intelligence.
 */
struct ThreatIntelSummary {
    int checked_domains = 0;     ///< Total hostnames queried via Threat Intel (VirusTotal)
    int malicious_domains = 0;   ///< Total hostnames flagged as malicious
};

/**
 * @brief Security alert generated by the Threat Detector.
 */
struct Alert {
    std::chrono::system_clock::time_point timestamp; ///< Time when alert occurred
    std::string source_ip;                           ///< Offending source IP address
    std::string description;                         ///< Detailed alert description
    std::string hostname;                            ///< Hostname involved, if any
    Severity severity = Severity::LOW;               ///< Risk severity level
    std::string dst_ip;                              ///< Destination IP address targeted
    std::string alert_type;                          ///< Identifier type (e.g. PORT_SCAN, HIGH_CONN)
    int repeat_count = 0;                            ///< Times alert has repeated
    std::uint16_t src_port = 0;                      ///< Source port involved
    std::uint16_t dst_port = 0;                      ///< Destination port targeted
    std::string payload_hex = "";                    ///< Hex dump representation of packet payload
};

/**
 * @brief Active rule in the simulated firewall system.
 */
struct FirewallRule {
    std::string target;      ///< Action target: DROP, REJECT, ACCEPT
    std::string ip;          ///< Blocked source IP address
    std::string reason;      ///< Reason for blocking
    std::uint64_t drops;     ///< Number of HIGH alerts that asked for this block
};

/**
 * @brief Thread-safe snapshot of all running statistics for dashboard display or reporting.
 */
struct StatsSnapshot {
    std::uint64_t total_packets = 0;            ///< Cumulative packets processed
    std::uint64_t total_bytes = 0;              ///< Cumulative bytes processed
    std::uint64_t tcp_packets = 0;              ///< Cumulative TCP packets
    std::uint64_t udp_packets = 0;              ///< Cumulative UDP packets
    std::uint64_t other_packets = 0;            ///< Cumulative non-TCP/UDP packets
    std::uint64_t active_flows = 0;            ///< Current size of flow tracking table
    double bytes_per_sec = 0.0;                 ///< Current network throughput (bytes/sec)
    double packets_per_sec = 0.0;               ///< Current packet rate (packets/sec)
    std::map<std::string, std::uint64_t> traffic_by_class; ///< Total bytes categorized by traffic class
    std::map<std::string, std::uint64_t> top_domains;      ///< Top requested hostnames and counts
    std::map<std::string, std::uint64_t> top_talkers;      ///< Top source IPs and total bytes sent
    std::vector<Flow> recent_flows;             ///< Last N active flows
    std::vector<Alert> alerts;                  ///< Generated security alerts
    std::vector<DnsQuery> dns_queries;          ///< Recorded DNS queries
    std::vector<FirewallRule> firewall_rules;    ///< Active firewall blocklists
    std::string firewall_mode = "passive";      ///< "passive" or "sdn"
    std::string blocklist_file;                 ///< Where block requests go in sdn mode
    ThreatIntelSummary threat_intel;            ///< Threat intelligence stats
};

/**
 * @brief Convert Protocol enum to human readable string.
 */
[[nodiscard]] std::string protocolToString(Protocol protocol);

/**
 * @brief Convert Severity enum to human readable string.
 */
[[nodiscard]] std::string severityToString(Severity severity);

/**
 * @brief Format a time_point into a human readable YYYY-MM-DD HH:MM:SS string.
 */
[[nodiscard]] std::string formatTime(std::chrono::system_clock::time_point time);

} // namespace PacMan

#endif // PACMAN_TYPES_H
